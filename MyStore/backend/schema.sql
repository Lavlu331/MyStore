CREATE PROCEDURE `sp_daily_low_stock_check`()
BEGIN
    INSERT INTO notifications (
        user_id,
        title,
        message,
        notification_type,
        product_id,
        warehouse_id
    )
    SELECT
        u.id,
        'Daily Low Stock Alert',
        CONCAT(
            p.name,
            ' has only ',
            wi.quantity,
            ' units left in ',
            w.name
        ),
        'low_stock',
        p.id,
        w.id
    FROM warehouse_inventory wi
    JOIN products p ON p.id = wi.product_id
    JOIN warehouses w ON w.id = wi.warehouse_id
    CROSS JOIN users u
    WHERE wi.quantity <= wi.low_stock_threshold
      AND u.role IN ('admin', 'inventory_manager')
      AND u.is_active = TRUE
      AND NOT EXISTS (
          SELECT 1
          FROM notifications n
          WHERE n.user_id = u.id
            AND n.product_id = p.id
            AND n.warehouse_id = w.id
            AND n.notification_type = 'low_stock'
            AND n.created_at >= NOW() - INTERVAL 1 DAY
      );
END ;;
